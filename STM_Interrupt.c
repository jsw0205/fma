/**********************************************************************************************************************
 * \file STM_Interrupt.c
 *********************************************************************************************************************/

#include "STM_Interrupt.h"
#include "Bsp.h"
#include "IfxStm.h"

/*********************************************************************************************************************/
/*------------------------------------------------------Macros-------------------------------------------------------*/
/*********************************************************************************************************************/
#define ISR_PRIORITY_STM        40
#define STM                     &MODULE_STM0

/*********************************************************************************************************************/
/*-------------------------------------------------Global variables--------------------------------------------------*/
/*********************************************************************************************************************/
IfxStm_CompareConfig g_STMConf;
Ifx_TickTime g_ticksFor100us;

volatile uint32 loop_cnt = 0;
volatile uint32 global_100us_cnt = 0;

/*********************************************************************************************************************/
/*------------------------------------------------Function Prototypes------------------------------------------------*/
/*********************************************************************************************************************/
void initSTM(void);

/*********************************************************************************************************************/
/*---------------------------------------------Function Implementations----------------------------------------------*/
/*********************************************************************************************************************/
IFX_INTERRUPT(isrSTM, 0, ISR_PRIORITY_STM);

void isrSTM(void)
{
    IfxStm_increaseCompare(STM, g_STMConf.comparator,
                           (uint32)g_ticksFor100us);

    loop_cnt++;
    global_100us_cnt++;
}

void initSTM(void)
{
    IfxStm_initCompareConfig(&g_STMConf);

    g_STMConf.triggerPriority = ISR_PRIORITY_STM;
    g_STMConf.typeOfService   = IfxSrc_Tos_cpu0;
    g_STMConf.ticks           = (uint32)g_ticksFor100us;

    IfxStm_initCompare(STM, &g_STMConf);
}

void initPeripherals(void)
{
    g_ticksFor100us =
        IfxStm_getTicksFromMicroseconds(BSP_DEFAULT_TIMER, 100);

    initSTM();
}
